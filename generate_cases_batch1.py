def make_case(cid, name, source_type, source_work, author, region, era,
              status, summary, full_story, relations, timeline, ending,
              characters, trick_desc, trick_types, mechanisms, info_gap,
              red_herring, difficulty, clues, game_design=None):
    case = {
        "id": cid,
        "基本信息": {
            "案件名称": name,
            "来源类型": source_type,
            "来源作品/事件": source_work,
            "作者/创作者": author,
            "地区": region,
            "年代": era,
            "案件状态": status,
            "一句话简介": summary,
            "参考链接": []
        },
        "故事视图": {
            "故事摘要": summary,
            "完整故事": full_story,
            "人物关系": relations,
            "关键时间线": timeline,
            "结局/真相": ending,
            "角色档案": characters
        },
        "设计视图": {
            "核心诡计简述": trick_desc,
            "诡计类型": trick_types,
            "可复用机制": mechanisms,
            "信息差分析": info_gap,
            "红鲱鱼/误导": red_herring,
            "难度评分": difficulty,
            "线索链": clues
        },
        "游戏设计": game_design or {},
        "元数据": {
            "录入状态": "故事完成",
            "录入日期": TODAY,
            "最后更新": TODAY,
            "飞书记录ID": "",
            "版本": 1
        }
    }
    return case

def save_case(case):
    stype = case["基本信息"]["来源类型"]
    region = case["基本信息"]["地区"]
    name = case["基本信息"]["案件名称"]
    # 清理文件名非法字符
    safe_name = "".join(c for c in name if c not in '<>:"/\\|?*')
    dir_path = os.path.join(CASES_DIR, stype, region)
    os.makedirs(dir_path, exist_ok=True)
    filepath = os.path.join(dir_path, f"{safe_name}.json")
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(case, f, ensure_ascii=False, indent=2)
    print(f"  保存: {filepath}")

def diff(d1, d2, d3, comp):
    return {"线索密度": d1, "误导数量": d2, "诡计隐蔽度": d3, "综合": comp}

def clue(cid, content, ctype, conclusion, timing):
    return {"线索编号": cid, "线索内容": content, "线索类型": ctype,
            "指向结论": conclusion, "出现时机": timing}

def char(name, identity, relation, motive, action):
    return {"姓名": name, "身份": identity, "与案件关系": relation,
            "动机": motive, "关键行为": action}

