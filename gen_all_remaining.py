def save(case):
    st=case["基本信息"]["来源类型"]; rg=case["基本信息"]["地区"]; nm=case["基本信息"]["案件名称"]
    safe="".join(c for c in nm if c not in '<>:"/\\|?*')
    dp=os.path.join(CASES_DIR,st,rg); os.makedirs(dp,exist_ok=True)
    with open(os.path.join(dp,f"{safe}.json"),"w",encoding="utf-8") as f: json.dump(case,f,ensure_ascii=False,indent=2)

