function processFile(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf-8');
    const data = JSON.parse(content);
    const name = data.基本信息?.案件名称 || path.basename(filePath, '.json');

    // 已有发表年份则跳过
    if (data.基本信息 && data.基本信息.发表年份) {
      return { skipped: true, name };
    }

    const year = YEAR_MAP[name];
    if (year) {
      data.基本信息.发表年份 = year;
      fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf-8');
      return { updated: true, name, year };
    }
    return { missing: true, name };
  } catch (e) {
    return { error: true, name: filePath, message: e.message };
  }
}

function walkDir(dir) {
  const results = [];
  const items = fs.readdirSync(dir);
  for (const item of items) {
    const fullPath = path.join(dir, item);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      results.push(...walkDir(fullPath));
    } else if (item.endsWith('.json')) {
      results.push(fullPath);
    }
  }
  return results;
}

// 主流程
const files = walkDir(CASES_DIR);
console.log(`找到 ${files.length} 个案件文件\n`);

let updated = 0, skipped = 0, missing = 0, errors = 0;
const missingList = [];

for (const file of files) {
  const result = processFile(file);
  if (result.updated) { updated++; }
  else if (result.skipped) { skipped++; }
  else if (result.missing) { missing++; missingList.push(result.name); }
  else if (result.error) { errors++; console.log(`错误: ${result.name} - ${result.message}`); }
}

console.log(`=== 处理完成 ===`);
console.log(`已更新: ${updated}`);
console.log(`已跳过(已有年份): ${skipped}`);
console.log(`未找到年份: ${missing}`);
console.log(`错误: ${errors}`);

if (missingList.length > 0) {
  console.log(`\n未找到年份的案件:`);
  missingList.forEach(n => console.log(`  - ${n}`));
}
