# 读取原文件作为模板
with open(os.path.join(CASES_DIR, "ZOO.json"), "r", encoding="utf-8") as f:
    template = json.load(f)


def make_case(story_name, intro, summary, full_story, characters, timeline,
              truth, trick_desc, trick_types, mechanisms, info_gap, red_herring,
              difficulty, clue_chain, character_profiles, relations):
    """创建一个案例字典"""
    case = copy.deepcopy(template)
    
    # 基本信息
    case["基本信息"]["案件名称"] = story_name
    case["基本信息"]["来源作品/事件"] = f"ZOO（{story_name}）"
    case["基本信息"]["作者/创作者"] = "乙一（安达宽高）"
    case["基本信息"]["地区"] = "日本"
    case["基本信息"]["年代"] = "2003年"
    case["基本信息"]["案件状态"] = "已结案"
    case["基本信息"]["一句话简介"] = intro
    case["基本信息"]["参考链接"] = []
    
    # 故事视图
    case["故事视图"]["故事摘要"] = summary
    case["故事视图"]["完整故事"] = full_story
    case["故事视图"]["人物关系"] = relations
    case["故事视图"]["关键时间线"] = timeline
    case["故事视图"]["结局/真相"] = truth
    case["故事视图"]["角色档案"] = character_profiles
    
    # 设计视图
    case["设计视图"]["核心诡计简述"] = trick_desc
    case["设计视图"]["诡计类型"] = trick_types
    case["设计视图"]["可复用机制"] = mechanisms
    case["设计视图"]["信息差分析"] = info_gap
    case["设计视图"]["红鲱鱼/误导"] = red_herring
    case["设计视图"]["难度评分"] = difficulty
    case["设计视图"]["线索链"] = clue_chain
    
    # 游戏设计 - 保持通用
    case["游戏设计"]["游戏平台"] = "通用"
    case["游戏设计"]["玩法类型"] = "短篇推理/心理惊悚"
    case["游戏设计"]["核心玩法机制"] = "阅读叙事→发现矛盾→揭示反转"
    case["游戏设计"]["关卡结构"] = "单章节短篇"
    case["游戏设计"]["玩家引导方式"] = "第一人称/受限视角叙事"
    case["游戏设计"]["推理系统设计"] = "依靠叙事中的细节矛盾进行推理"
    case["游戏设计"]["可复用游戏模板"] = "短篇反转叙事模板"
    
    # 元数据
    case["元数据"]["录入状态"] = "已完成"
    case["元数据"]["录入日期"] = TODAY
    case["元数据"]["最后更新"] = TODAY
    case["元数据"]["飞书记录ID"] = ""
    case["元数据"]["版本"] = 1
    
    return case


