// 通用案件生成器
function makeCase({ name, sourceType, work, creator, region, continent, year, status, summary, fullStory, characters, timeline, ending, trick, trickTypes, mechanisms, infoGap, redHerring, difficulty, clues, gameAdapt, platforms, playTypes, templates }) {
  return {
    id: name.replace(/[^\w\u4e00-\u9fa5]/g, '-').toLowerCase(),
    基本信息: {
      案件名称: name,
      来源类型: sourceType,
      来源作品: work || name,
      作者: creator,
      大洲: continent,
      地区: region,
      年代: `${Math.floor(year/10)*10}年代`,
      发表年份: year,
      案件状态: status || '已完结',
      一句话简介: summary,
      参考链接: [
        { 标题: `${name} - 维基百科`, URL: `https://zh.wikipedia.org/wiki/${encodeURIComponent(name)}`, 类型: '百科' },
        { 标题: `${name} - 豆瓣`, URL: `https://search.douban.com/book/subject_search?search_text=${encodeURIComponent(name)}`, 类型: '书评' },
      ],
      推荐视频: [
        { 标题: `${name} 深度解析`, URL: `https://search.bilibili.com/all?keyword=${encodeURIComponent(name)}`, 来源: 'B站', 视频类型: '解说' },
        { 标题: `${name} analysis`, URL: `https://www.youtube.com/results?search_query=${encodeURIComponent(name)}`, 来源: 'YouTube', 视频类型: '评测' },
      ],
    },
    故事视图: {
      故事摘要: summary,
      完整故事: fullStory,
      人物关系: characters.map(c => `${c.姓名}（${c.身份}）：${c.与案件关系}`).join('；'),
      关键时间线: timeline,
      结局: ending,
      角色档案: characters,
    },
    设计视图: {
      核心诡计简述: trick,
      诡计类型: trickTypes,
      可复用机制: mechanisms,
      信息差分析: infoGap,
      红鲱鱼: redHerring,
      难度评分: difficulty,
      线索链: clues,
      游戏化改编建议: gameAdapt,
    },
    游戏设计: {
      游戏平台: platforms,
      玩法类型: playTypes,
      核心玩法机制: mechanisms,
      可复用游戏模板: templates,
    },
    元数据: {
      录入状态: '完整',
      录入日期: TODAY,
      最后更新: TODAY,
      版本: 1,
    },
  };
}

// 角色档案快捷生成
function char(name, identity, relation, motive, action) {
  return { 姓名: name, 身份: identity, 与案件关系: relation, 动机: motive, 关键行为: action };
}

// 线索快捷生成
function clue(id, content, type, conclusion, timing) {
  return { 线索编号: id, 线索内容: content, 线索类型: type, 指向结论: conclusion, 出现时机: timing };
}

// 难度快捷生成
function diff(density, mislead, trick, overall) {
  return { 线索密度: density, 误导数量: mislead, 诡计隐蔽度: trick, 综合: overall };
}

