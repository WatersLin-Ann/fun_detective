fixed_ending = 0
fixed_full = 0
fixed_timeline = 0

for slug in set(list(endings.keys()) + list(full_stories.keys()) + list(timelines.keys())):
    path = os.path.join(CASES_DIR, slug + '.json')
    if not os.path.exists(path):
        continue
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    story = data.get('故事视图', {})
    modified = False
    
    if slug in endings and not story.get('结局'):
        story['结局'] = endings[slug]
        modified = True
        fixed_ending += 1
    
    if slug in full_stories and not story.get('完整故事'):
        story['完整故事'] = full_stories[slug]
        modified = True
        fixed_full += 1
    
    if slug in timelines and not story.get('关键时间线'):
        story['关键时间线'] = timelines[slug]
        modified = True
        fixed_timeline += 1
    
    if modified:
        data['故事视图'] = story
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write('\n')

