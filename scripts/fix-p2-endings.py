for slug, ending in endings.items():
    path = os.path.join(CASES_DIR, slug + '.json')
    if not os.path.exists(path):
        skipped += 1
        continue
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    story = data.get('故事视图', {})
    if not story.get('结局/真相'):
        story['结局/真相'] = ending
        data['故事视图'] = story
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write('\n')
        fixed += 1
        print(f'  补全结局: {slug}')
    else:
        skipped += 1

