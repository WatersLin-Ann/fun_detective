fixed_summary = 0
fixed_timeline = 0

for slug, summary in summaries.items():
    path = os.path.join(CASES_DIR, slug + '.json')
    if not os.path.exists(path):
        continue
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    story = data.get('故事视图', {})
    modified = False
    if not story.get('故事摘要'):
        story['故事摘要'] = summary
        modified = True
        fixed_summary += 1
    if slug in timelines and not story.get('关键时间线'):
        story['关键时间线'] = timelines[slug]
        modified = True
        fixed_timeline += 1
    if modified:
        data['故事视图'] = story
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write('\n')
        print(f'  补全: {slug}')

print(f'\n补全故事摘要: {fixed_summary} 个')
