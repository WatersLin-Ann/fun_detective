const C=(n,i,r,m,a)=>({姓名:n,身份:i,与案件关系:r,动机:m,关键行为:a});
const L=(id,c,t,con,tm)=>({线索编号:id,线索内容:c,线索类型:t,指向结论:con,出现时机:tm});
const D=(d,m,t,o)=>({线索密度:d,误导数量:m,诡计隐蔽度:t,综合:o});

function write(cases, type) {
  let count = 0;
  cases.forEach(c => {
    const dir = path.join(ROOT, 'cases', type, c.region);
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, {recursive: true});
    const fp = path.join(dir, `${c.name}.json`);
    if (!fs.existsSync(fp)) {
      fs.writeFileSync(fp, JSON.stringify(makeCase({...c, sourceType:type}), null, 2), 'utf-8');
      count++;
    }
  });
  console.log(`${type}: 新增 ${count} 个`);
}

