    故事视图: { 故事摘要:o.summary, 完整故事:o.fullStory, 人物关系:o.characters.map(c=>`${c.姓名}（${c.身份}）：${c.与案件关系}`).join('；'), 关键时间线:o.timeline, 结局:o.ending, 角色档案:o.characters },
